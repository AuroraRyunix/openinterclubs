  def locale, do: Process.get(:oi_locale, "nl")

  def put_locale(l) when l in @locales, do: Process.put(:oi_locale, l)
  def put_locale(_), do: Process.put(:oi_locale, "nl")

  @doc "Translate a Dutch interface text into the current locale."
  def t(text) do
    case locale() do
      "fr" -> Map.get(@fr, text, text)
      "en" -> Map.get(@en, text, text)
      _ -> text
    end
  end

  @doc "Translate, then fill `%{name}` placeholders: t(\"Ronde %{n}\", n: 3)."
  def t(text, bindings) do
    Enum.reduce(bindings, t(text), fn {k, v}, acc ->
      String.replace(acc, "%{#{k}}", to_string(v))
    end)
  end
